def python_path(env: Path) -> Path:
    return env / ("Scripts/python.exe" if os.name == "nt" else "bin/python")


def run(
    args: list[str], *, cwd: Path, output: bool = False, env: dict[str, str] | None = None
) -> str:
    """Run without a shell; capture stdout when requested and raise on failure.

    The child shares terminal signals. Let it finish cleanup after Ctrl-C;
    a second interruption terminates it. Environment defaults to inheritance.
    """
    with subprocess.Popen(
        args, cwd=cwd, text=True, env=env, stdout=subprocess.PIPE if output else None
    ) as process:
        try:
            try:
                stdout, _ = process.communicate()
            except KeyboardInterrupt:
                process.communicate()
                raise
        except BaseException:
            if process.poll() is None:
                process.kill()
            process.wait()
            raise
        if process.returncode:
            raise subprocess.CalledProcessError(process.returncode, args, output=stdout)
    return (stdout or "").strip()


def write_if_changed(dest: Path, text: str) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    if not dest.exists() or dest.read_text(encoding="utf8") != text:
        dest.write_text(text, encoding="utf8")


def atomic_json(path: Path, document: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w", dir=path.parent, encoding="utf8", prefix=".state-", suffix=".tmp", delete=False
    ) as f:
        tmp = Path(f.name)
        json.dump(document, f, indent=2, sort_keys=True)
        f.write("\n")
    try:
        os.replace(tmp, path)
    finally:
        tmp.unlink(missing_ok=True)


def selection_text(projects: list[dict[str, Any]]) -> str:
    """Record the selected Git sources for audit and drift detection."""
    if catalog.yaml is None:
        raise catalog.WorkspaceError("PyYAML is required for source selection")
    entries = [{k: p[k] for k in ("name", "url", "revision", "path")} for p in projects]
    return "# Generated by AutoSpan Workspace. Do not edit.\n" + catalog.yaml.safe_dump(
        {"schema": 1, "repositories": entries}, sort_keys=False
    )


def generated_selection(root: Path) -> Path:
    return root / ".generated" / "selection.yaml"


def checkout_path(root: Path, project: dict[str, Any]) -> Path:
    """All managed Git repositories live INSIDE this workspace."""
    return root / "repos" / project["path"]


def state_file(root: Path) -> Path:
    return root / ".generated" / "state.json"


def get_state(root: Path) -> dict[str, Any] | None:
    try:
        data = json.loads(state_file(root).read_text(encoding="utf8"))
    except (ValueError, OSError):
        return None
    if not isinstance(data, dict) or data.get("schema") != 1:
        return None
    for key in ("selected", "distributions"):
        value = data.get(key)
        if not isinstance(value, list) or not all(isinstance(item, str) for item in value):
            return None
    heads = data.get("heads")
    if not isinstance(heads, dict) or not all(
        isinstance(name, str) and isinstance(sha, str) and re.fullmatch(r"[0-9a-f]{40}", sha)
        for name, sha in heads.items()
    ):
        return None
    if not isinstance(data.get("env"), str):
        return None
    for key, length in (("env_key", 20), ("selection_sha256", 64)):
        value = data.get(key)
        if not isinstance(value, str) or not re.fullmatch(rf"[0-9a-f]{{{length}}}", value):
            return None
    return data


def load_selection(
    root: Path, *, persist: bool = False, config_path: Path | None = None
) -> tuple[dict, dict, list]:
    doc = catalog.read_catalog(root / "repos.local.yaml", root)
    catalog.write_generated_menu(root, doc)
    try:
        import kconfiglib
    except ImportError as exc:
        raise catalog.WorkspaceError("Kconfiglib missing; run `make tools`") from exc
    previous = Path.cwd()
    try:
        os.chdir(root)
        kc = kconfiglib.Kconfig("Kconfig", warn=False)
        source = config_path or root / ".config"
        if source.exists():
            kc.load_config(str(source))
        flags = {
            x.name: x.str_value == "y" for x in kc.unique_defined_syms if x.type == kconfiglib.BOOL
        }
        projects = catalog.selected(doc, flags)
        if persist:
            kc.write_config(".config")
    finally:
        os.chdir(previous)
    return doc, flags, projects


def tools(root: Path) -> None:
    with operation_lock(root):
        _install_tools(root)


def _install_tools(root: Path) -> None:
    req_path = root / TOOLS_REQUIREMENTS
    if not req_path.exists():
        raise catalog.WorkspaceError(f"Missing {TOOLS_REQUIREMENTS}")
    digest = hashlib.sha256(req_path.read_bytes() + sys.version.encode()).hexdigest()
    dest = root / ".tools"
    executable = python_path(dest)
    marker = dest / ".ready"
    if executable.exists() and marker.exists() and marker.read_text() == digest:
        print("Workspace tools already installed (pinned versions).")
        return
    if not executable.exists():
        venv.EnvBuilder(with_pip=True).create(dest)
    run([str(executable), "-I", "-m", "pip", "install", "-r", str(req_path)], cwd=root)
    # Verify that the tools import correctly before setting the readiness marker.
    run([str(executable), "-c", "import kconfiglib, yaml, pytest"], cwd=root)
    write_if_changed(marker, digest)


def git(root: Path, *args: str, output: bool = False) -> str:
    return run(["git", *args], cwd=root, output=output)


def git_head(path: Path) -> str:
    if not (path / ".git").exists():
        raise catalog.WorkspaceError(f"Not a Git checkout: {path}")
    return git(path, "-C", str(path), "rev-parse", "HEAD", output=True)


def assert_safe_checkouts(
    root: Path, projects: list[dict[str, Any]], *, require_clean: bool = True
) -> None:
    """Preflight all selected sources before doing any fetch or checkout."""
    base = root / "repos"
    if base.is_symlink():
        raise catalog.WorkspaceError("repos/ must be a directory, not a symlink")
    if base.exists() and not base.is_dir():
        raise catalog.WorkspaceError("repos/ exists but is not a directory")
    for p in projects:
        relative = Path(p["path"])
        for depth in range(1, len(relative.parts) + 1):
            candidate = base.joinpath(*relative.parts[:depth])
            if candidate.is_symlink():
                raise catalog.WorkspaceError(f"{p['name']}: symlink checkout path is not permitted")
        dest = checkout_path(root, p)
        if not dest.exists():
            continue
        if not (dest / ".git").exists():
            raise catalog.WorkspaceError(f"{dest} exists but is not a Git checkout")
        origin = git(root, "-C", str(dest), "remote", "get-url", "origin", output=True)
        if origin != p["url"]:
            raise catalog.WorkspaceError(
                f"{p['name']}: checkout origin is {origin!r}, but catalog requests {p['url']!r}"
            )
        changes = (
            git(root, "-C", str(dest), "status", "--porcelain", output=True)
            if require_clean
            else ""
        )
        if changes:
            raise catalog.WorkspaceError(
                f"{p['name']} contains uncommitted changes; refusing to update it:\n{changes}"
            )


def resolve_revision(root: Path, dest: Path, revision: str) -> str:
    """Prefer remote branches, then tags, then a local commit SHA."""
    refs = [f"refs/remotes/origin/{revision}^{{commit}}", f"refs/tags/{revision}^{{commit}}"]
    if re.fullmatch(r"[0-9a-fA-F]{40}", revision):
        refs.append(revision + "^{commit}")
    for ref in refs:
        result = subprocess.run(
            ["git", "-C", str(dest), "rev-parse", "--verify", "--quiet", ref],
            cwd=root,
            text=True,
            capture_output=True,
            check=False,
        )
        if result.returncode == 0:
            return result.stdout.strip()
    raise catalog.WorkspaceError(
        f"{dest.name}: revision {revision!r} not found among fetched branches/tags/commits"
    )


def fetch_revision(root: Path, dest: Path, revision: str) -> str:
    """Fetch and resolve a requested revision without changing HEAD."""
    git(root, "-C", str(dest), "fetch", "--tags", "origin")
    try:
        return resolve_revision(root, dest, revision)
    except catalog.WorkspaceError:
        if not re.fullmatch(r"[0-9a-fA-F]{40}", revision):
            raise
        git(root, "-C", str(dest), "fetch", "origin", revision)
        return resolve_revision(root, dest, revision)


def sync_sources(root: Path, projects: list[dict[str, Any]]) -> dict[str, str]:
    """Resolve every requested revision before updating existing worktrees."""
    assert_safe_checkouts(root, projects)
    (root / "repos").mkdir(exist_ok=True)
    resolved = []
    for project in projects:
        dest = checkout_path(root, project)
        created = not dest.exists()
        if created:
            dest.parent.mkdir(parents=True, exist_ok=True)
            git(root, "clone", "--origin", "origin", "--", project["url"], str(dest))
        sha = fetch_revision(root, dest, project["revision"])
        resolved.append((project, dest, sha, created))
    heads = {}
    for project, dest, sha, created in resolved:
        if created or git_head(dest) != sha:
            git(root, "-C", str(dest), "checkout", "--detach", sha)
        heads[project["name"]] = git_head(dest)
    return heads


def check_package_metadata(dest: Path, project: dict[str, Any]) -> None:
    pkg = project["python"]
    if not pkg:
        return
    toml = dest / "pyproject.toml"
    setup_py = dest / "setup.py"
    if not toml.exists():
        if not setup_py.exists():
            raise catalog.WorkspaceError(
                f"{project['name']}: expected a Python package (pyproject.toml or setup.py)"
            )
        if project["extras"]:
            raise catalog.WorkspaceError(
                f"{project['name']}: cannot validate extras without pyproject.toml"
            )
        return
    try:
        data = tomllib.loads(toml.read_text(encoding="utf8"))
    except (ValueError, OSError) as exc:
        raise catalog.WorkspaceError(f"{project['name']}: invalid pyproject.toml: {exc}") from exc
    metadata = data.get("project", {})
    if not isinstance(metadata, dict):
        raise catalog.WorkspaceError(f"{project['name']}: project metadata must be a table")
    declared = metadata.get("name")
    if declared is not None and not isinstance(declared, str):
        raise catalog.WorkspaceError(
            f"{project['name']}: project distribution name must be a string"
        )

    def normalize(value: str) -> str:
        return re.sub(r"[-_.]+", "-", value).lower()

    if declared is not None and normalize(declared) != normalize(pkg["distribution"]):
        raise catalog.WorkspaceError(
            f"{project['name']}: configured distribution {pkg['distribution']!r} "
            f"does not match pyproject.toml name {declared!r}"
        )
    optional = metadata.get("optional-dependencies", {})
    if not isinstance(optional, dict):
        raise catalog.WorkspaceError(f"{project['name']}: optional-dependencies must be a table")
    extras = set(optional)
    missing = set(project["extras"]) - extras
    if missing:
        raise catalog.WorkspaceError(
            f"{project['name']}: configured extras {sorted(missing)} missing from pyproject.toml"
        )


def package_name(directory: Path) -> str:
    """Read distribution identity of a separately packaged scenario project."""
    try:
        metadata = tomllib.loads((directory / "pyproject.toml").read_text(encoding="utf8"))
    except (ValueError, OSError) as exc:
        raise catalog.WorkspaceError(
            f"Invalid scenario package metadata: {directory}: {exc}"
        ) from exc
    project = metadata.get("project", {})
    name = project.get("name") if isinstance(project, dict) else None
    if not isinstance(name, str) or not catalog.DIST.fullmatch(name):
        raise catalog.WorkspaceError(f"Scenario package missing project.name: {directory}")
    return name


def env_fingerprint(
    projects: list[dict[str, Any]],
    heads: dict[str, str],
    flags: dict[str, bool],
    root: Path,
    *,
    checkouts: dict[str, Path] | None = None,
    extra_packages: list[Path] | None = None,
) -> str:
    payload = {
        "projects": projects,
        "heads": heads,
        "package_metadata": {
            p["name"]: {
                file: hashlib.sha256(
                    ((checkouts or {}).get(p["name"], checkout_path(root, p)) / file).read_bytes()
                ).hexdigest()
                for file in ("pyproject.toml", "setup.cfg", "setup.py")
                if ((checkouts or {}).get(p["name"], checkout_path(root, p)) / file).is_file()
            }
            for p in projects
            if p["python"]
        },
        "checkout_paths": {name: str(path) for name, path in (checkouts or {}).items()},
        "editable": flags.get("AUTOSPAN_EDITABLE", True),
        "python": sys.version,
        "platform": sys.platform,
        "root": str(root.resolve()),
        "test_runner": TEST_PYTEST_VERSION,
        "test_reporter": TEST_HTML_VERSION,
        "requirements_tools": hashlib.sha256((root / TOOLS_REQUIREMENTS).read_bytes()).hexdigest(),
    }
    if extra_packages:
        payload["scenario_packages"] = [
            {
                "name": package_name(package),
                "path": str(package),
                "metadata": {
                    filename: hashlib.sha256((package / filename).read_bytes()).hexdigest()
                    for filename in ("pyproject.toml", "setup.cfg", "setup.py")
                    if (package / filename).is_file()
                },
            }
            for package in extra_packages
        ]
    return hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()[:20]


def environment(
    root: Path,
    projects: list[dict[str, Any]],
    flags: dict[str, bool],
    heads: dict[str, str],
    *,
    checkouts: dict[str, Path] | None = None,
    base: Path | None = None,
    extra_packages: list[Path] | None = None,
) -> tuple[str, Path]:
    key = env_fingerprint(
        projects,
        heads,
        flags,
        root,
        checkouts=checkouts,
        extra_packages=extra_packages,
    )
    base = base or root / ".envs"
    if base.is_symlink() or (base.exists() and not base.is_dir()):
        raise catalog.WorkspaceError(".envs/ must be a directory, not a symlink")
    base.mkdir(parents=True, exist_ok=True)
    wanted = [p["python"]["distribution"] for p in projects if p["python"]]
    wanted += [package_name(p) for p in (extra_packages or [])]
    candidates = [base / key, *sorted(base.glob(key + "-*"))]
    for candidate in candidates:
        ready = candidate / ".ready"
        if candidate.is_symlink() or not ready.is_file() or not python_path(candidate).is_file():
            continue
        try:
            if ready.read_text(encoding="ascii") != key:
                continue
            check_installed(candidate, wanted)
        except (catalog.WorkspaceError, OSError, UnicodeError):
            continue
        print(f"Reusing prepared environment {candidate.name}")
        return key, candidate
    # Create at its permanent path; never delete a previous environment to repair it.
    env_dir = Path(tempfile.mkdtemp(prefix=key + "-", dir=base))
    try:
        venv.EnvBuilder(with_pip=True).create(env_dir)
        command = [
            str(python_path(env_dir)),
            "-I",
            "-m",
            "pip",
            "install",
            TEST_PYTEST_VERSION,
            TEST_HTML_VERSION,
        ]
        for project in projects:
            if not project["python"]:
                continue
            dest = (checkouts or {}).get(project["name"], checkout_path(root, project))
            check_package_metadata(dest, project)
            suffix = "[" + ",".join(project["extras"]) + "]" if project["extras"] else ""
            if flags.get("AUTOSPAN_EDITABLE", True):
                command.append("-e")
            command.append(str(dest) + suffix)
        for package in extra_packages or []:
            command.append(str(package))
        run(command, cwd=root)
        check_installed(env_dir, wanted)
        (env_dir / ".ready").write_text(key, encoding="ascii")
    except BaseException:
        shutil.rmtree(env_dir, ignore_errors=True)
        raise
    return key, env_dir


def check_installed(env_dir: Path, distributions: list[str]) -> None:
    script = "import importlib.metadata as m,sys; [m.version(x) for x in sys.argv[1:]]"
    try:
        run([str(python_path(env_dir)), "-I", "-c", script, *distributions], cwd=env_dir)
        run([str(python_path(env_dir)), "-I", "-m", "pip", "check"], cwd=env_dir, output=True)
    except subprocess.CalledProcessError as exc:
        details = (exc.stdout or "").strip()
        raise catalog.WorkspaceError(
            f"Python distributions or dependencies invalid in {env_dir}"
            + (f": {details}" if details else "")
        ) from exc


def check_plugins(env_dir: Path, names: list[str]) -> None:
    """Validate profile entry points without importing drivers or acquiring resources."""
    if not names:
        return
    script = (
        "import importlib.metadata as m,sys; "
        "available={ep.name for ep in m.entry_points(group='autospan.plugins')}; "
        "missing=set(sys.argv[1:])-available; "
        "sys.exit('Missing AutoSpan plugins: '+', '.join(sorted(missing)) if missing else 0)"
    )
    try:
        run([str(python_path(env_dir)), "-I", "-c", script, *names], cwd=env_dir)
    except subprocess.CalledProcessError as exc:
        raise catalog.WorkspaceError(
            "Profile requires unavailable AutoSpan plugin entry points"
        ) from exc


def bootstrap(root: Path) -> None:
    with operation_lock(root):
        _bootstrap(root)


def _bootstrap(root: Path) -> None:
    _, flags, selected = load_selection(root)
    assert_safe_checkouts(root, selected)
    heads = sync_sources(root, selected)
    _activate(root, selected, flags, heads)


def install(root: Path) -> None:
    """Prepare the selected environment from current sources without moving Git HEADs."""
    with operation_lock(root):
        _, flags, selected = load_selection(root)
        assert_safe_checkouts(root, selected, require_clean=False)
        heads = {p["name"]: git_head(checkout_path(root, p)) for p in selected}
        _activate(root, selected, flags, heads)


def _activate(
    root: Path, selected: list[dict[str, Any]], flags: dict[str, bool], heads: dict[str, str]
) -> None:
    rendered = selection_text(selected)
    # Package contracts are validated before any dependency installation.
    for project in selected:
        if project["python"]:
            check_package_metadata(checkout_path(root, project), project)
    key, env_dir = environment(root, selected, flags, heads)
    state = {
        "schema": 1,
        "selection_sha256": hashlib.sha256(rendered.encode()).hexdigest(),
        "selected": [p["name"] for p in selected],
        "heads": heads,
        "env_key": key,
        "env": str(env_dir),
        "distributions": [p["python"]["distribution"] for p in selected if p["python"]],
    }
    # Activate LAST. On install failure, retain the previous active env state.
    write_if_changed(generated_selection(root), rendered)
    atomic_json(state_file(root), state)
    print(f"Active environment: {env_dir}\nWorkspace synchronized. Run `make doctor`.")


def inspect(root: Path) -> list[str]:
    problems = []
    for tool in ("git",):
        if not shutil.which(tool):
            problems.append(f"Missing required program: {tool}")
    if not python_path(root / ".tools").exists():
        problems.append("Workspace tool environment missing (make tools)")
    try:
        _, flags, projects = load_selection(root)
        assert_safe_checkouts(root, projects, require_clean=False)
        rendered = selection_text(projects)
        path = generated_selection(root)
        if not path.is_file() or path.read_text(encoding="utf8") != rendered:
            problems.append("Source selection out of sync (run make install)")
    except (catalog.WorkspaceError, ImportError, OSError, subprocess.CalledProcessError) as exc:
        problems.append(str(exc))
        return problems
    state = get_state(root)
    if not state:
        problems.append("No active installation state (make bootstrap)")
        return problems
    if state.get("selection_sha256") != hashlib.sha256(rendered.encode()).hexdigest():
        problems.append("Selections changed since installation (make install)")
    if state.get("selected") != [p["name"] for p in projects]:
        problems.append("Selected repository set does not match active environment")
    if state.get("env_key") != env_fingerprint(projects, state.get("heads", {}), flags, root):
        problems.append("Python environment selection/features changed (make install)")
    for p in projects:
        try:
            if state.get("heads", {}).get(p["name"]) != git_head(checkout_path(root, p)):
                problems.append(
                    f"Checkout {p['name']} differs from active installation (make install)"
                )
        except (catalog.WorkspaceError, subprocess.CalledProcessError, OSError) as exc:
            problems.append(str(exc))
    env_dir = Path(state["env"])
    key = state["env_key"]
    expected = [p["python"]["distribution"] for p in projects if p["python"]]
    if state["distributions"] != expected:
        problems.append("Installed distribution selection does not match the catalog")
    if (
        env_dir.parent != root / ".envs"
        or env_dir.is_symlink()
        or (root / ".envs").is_symlink()
        or not (env_dir.name == key or env_dir.name.startswith(key + "-"))
        or not (env_dir / ".ready").is_file()
    ):
        problems.append("Active environment missing or invalid")
    else:
        try:
            if (env_dir / ".ready").read_text(encoding="ascii") != key:
                problems.append("Active environment readiness marker is invalid")
            else:
                check_installed(env_dir, expected)
        except (catalog.WorkspaceError, OSError, UnicodeError) as exc:
            problems.append(str(exc))
    return problems


def doctor(root: Path) -> bool:
    errors = inspect(root)
    if errors:
        print("Doctor: FAILED")
        for error in errors:
            print(" - " + error)
        return False
    state = get_state(root) or {}
    print(
        f"Doctor: OK ({len(state.get('selected', []))} components, active environment {state.get('env_key')})"
    )
    return True


def status(root: Path) -> None:
    state = get_state(root)
    print(f"Workspace: {root}")
    print(f"Git: {shutil.which('git') or 'missing'}")
    print(f"Tools: {'ready' if python_path(root / '.tools').exists() else 'missing'}")
    print(f"Active env: {state.get('env', 'none') if state else 'none'}")
    print("Installed components: " + (", ".join(state.get("selected", [])) if state else "(none)"))
    if state:
        try:
            _, _, selected = load_selection(root)
            paths = {p["name"]: p["path"] for p in selected}
        except (catalog.WorkspaceError, ImportError):
            paths = {}
        for name, sha in state.get("heads", {}).items():
            checkout = root / "repos" / paths[name] if name in paths else None
            dirty = ""
            if checkout is not None and (checkout / ".git").exists():
                try:
                    dirty = (
                        " [DIRTY]"
                        if run(
                            ["git", "-C", str(checkout), "status", "--porcelain"],
                            cwd=root,
                            output=True,
                        )
                        else " [clean]"
                    )
                except (OSError, subprocess.CalledProcessError):
                    dirty = " [git status unavailable]"
            print(f"  {name}: {sha[:12]}{dirty}")
    problems = inspect(root)
    if problems:
        print("Warnings: " + "; ".join(problems))


def freeze(root: Path) -> Path:
    if not doctor(root):
        raise catalog.WorkspaceError("Cannot freeze an unhealthy workspace")
    dest = root / ".generated" / "snapshot"
    dest.mkdir(parents=True, exist_ok=True)
    _, _, selected = load_selection(root)
    state = get_state(root) or {}
    source_catalog = catalog.read_catalog(root / "repos.local.yaml", root)
    frozen = {
        p["name"]: {
            **source_catalog["repositories"][p["name"]],
            "revision": state["heads"][p["name"]],
        }
        for p in selected
    }
    (dest / "sources-frozen.yaml").write_text(
        catalog.yaml.safe_dump({"schema": 1, "repositories": frozen}, sort_keys=False),
        encoding="utf8",
    )
    env_dir = Path((get_state(root) or {})["env"])
    (dest / "requirements-frozen.txt").write_text(
        run([str(python_path(env_dir)), "-m", "pip", "freeze"], cwd=root, output=True) + "\n"
    )
    if (root / ".config").exists():
        shutil.copy2(root / ".config", dest / ".config")
    shutil.copy2(root / "repos.local.yaml", dest / "repos.local.yaml")
    shutil.copy2(state_file(root), dest / "state.json")
    print(f"Wrote audit snapshot: {dest}")
    print(
        "WARNING: pip freeze of editable installs is path-dependent; this is NOT a portable lockfile."
    )
    return dest


def run_tests(
    root: Path,
    custom: list[str],
    options: list[str] | None = None,
    *,
    config: str | None = None,
) -> None:
    env_dir = active_environment(root)
    extra = options or []
    process_env = execution_environment(env_dir)
    if config is not None:
        bench = Path(config)
        if not bench.is_absolute():
            bench = root / bench
        if not bench.is_file():
            raise catalog.WorkspaceError(f"Bench configuration missing: {bench}")
        run_hosted_tests(
            [
                str(python_path(env_dir)),
                "-m",
                "autospan",
                "test",
                "--config",
                str(bench),
                "--",
                *custom,
                *extra,
            ],
            cwd=root,
            env=process_env,
        )
        return
    _, _, projects = load_selection(root)
    if custom:
        run_pytest(
            [str(python_path(env_dir)), "-m", "pytest", "--import-mode=importlib", *custom, *extra],
            cwd=root,
            env=process_env,
        )
        return
    suites = [p for p in projects if p["tests"]]
    if not suites:
        raise catalog.WorkspaceError(
            "No tests configured: add tests: [tests] to a repository or pass TEST_PATH"
        )
    for project in suites:
        print(f"Testing {project['name']}", flush=True)
        run_pytest(
            [str(python_path(env_dir)), "-m", "pytest", *project["tests"], *extra],
            cwd=checkout_path(root, project),
            env=process_env,
        )


def run_hosted_tests(args: list[str], *, cwd: Path, env: dict[str, str]) -> None:
    """Finish the HTML report after AutoSpan closes its evidence, even on failure."""
    _run_test_report(args, cwd=cwd, env=env, hosted=True)


def run_pytest(args: list[str], *, cwd: Path, env: dict[str, str]) -> None:
    """Stage plain pytest reports with the same failure and collection guarantees."""
    _run_test_report(args, cwd=cwd, env=env, hosted=False)


def _run_test_report(args: list[str], *, cwd: Path, env: dict[str, str], hosted: bool) -> None:
    options = args[args.index("--") + 1 :] if hosted else args
    destination = None
    for index, value in enumerate(options):
        if value.startswith("--html="):
            destination = value.partition("=")[2]
        elif value == "--html" and index + 1 < len(options):
            destination = options[index + 1]
    if any(value in options for value in ("--collect-only", "--collectonly", "--co")):
        # pytest-html writes even during collection. Its final empty option
        # disables output while leaving the plugin's other options recognized.
        # Also override project addopts/PYTEST_ADDOPTS when no explicit path was
        # supplied. Every prepared workspace test environment includes pytest-html.
        print("Collecting selected scenarios (no hardware acquisition)", flush=True)
        # Avoid rewriting stdlib html and prevent a second registration through
        # pytest-html's short entry-point name when plugin autoload is enabled.
        run([*args, "-p", "no:html", "-p", "pytest_html.plugin", "--html="], cwd=cwd, env=env)
        print("Collection completed; existing report preserved", flush=True)
        return
    if not destination:
        run(args, cwd=cwd, env=env)
        return
    output = Path(os.path.expandvars(destination)).expanduser()
    if not output.is_absolute():
        output = cwd / output
    try:
        output.unlink(missing_ok=True)
        output.parent.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        raise catalog.WorkspaceError(
            f"Cannot replace previous HTML report {output}; tests not started: {exc}"
        ) from exc
    # Each child writes a private report beside the destination, preserving
    # relative artifact links. Concurrent runs only publish complete documents.
    with tempfile.NamedTemporaryFile(
        dir=output.parent, prefix=".report-", suffix=".html", delete=False
    ) as handle:
        pending_report = Path(handle.name)
    failure = None
    reporting_error = None
    evidence = None
    try:
        try:
            command = args
            if hosted:
                parent = cwd / "artifacts" / "evidence"
                parent.mkdir(parents=True, exist_ok=True)
                evidence = Path(tempfile.mkdtemp(prefix="report-", dir=parent))
                separator = args.index("--")
                command = [
                    *args[:separator],
                    "--evidence-dir",
                    str(evidence),
                    *args[separator:],
                ]
            command = [*command, f"--html={pending_report}"]
            # Report-path filtering uses a pipe, so pytest cannot detect the
            # operator's terminal. Restore its usual colors for interactive
            # runs without overriding an explicit color preference.
            if (
                sys.stdout.isatty()
                and "NO_COLOR" not in env
                and env.get("PY_COLORS") != "0"
                and not any(value == "--color" or value.startswith("--color=") for value in options)
            ):
                command.append("--color=yes")
            print("Running selected scenarios", flush=True)
            _run_report_child(command, cwd=cwd, env=env, hidden=str(pending_report))
        except (subprocess.CalledProcessError, OSError, KeyboardInterrupt) as exc:
            failure = exc
        print("Finalizing report and evidence", flush=True)
        try:
            if hosted:
                manifests = list(evidence.glob("*/manifest.json")) if evidence is not None else []
                if len(manifests) != 1:
                    raise ValueError("Expected one finalized AutoSpan evidence manifest")
                reports.enrich(pending_report, manifests[0].parent)
            elif not pending_report.read_text(encoding="utf-8").strip():
                raise ValueError("pytest did not produce an HTML report")
        except Exception as exc:
            reporting_error = exc
            reason = _report_message(
                str(exc) + (f"; test command failed: {failure}" if failure is not None else ""),
                pending_report,
            )
            print(f"HTML evidence report incomplete: {reason}", file=sys.stderr)
            try:
                reports.mark_incomplete(pending_report, reason)
            except Exception as diagnostic:
                print(f"Cannot mark incomplete HTML report: {diagnostic}", file=sys.stderr)
        try:
            reports.publish(pending_report, output)
        except OSError as exc:
            reporting_error = exc
            print(
                f"Cannot publish HTML report {output}: {exc}; retained {pending_report}",
                file=sys.stderr,
            )
        else:
            print(f"Final HTML report: {output.resolve().as_uri()}", flush=True)
        if failure is not None:
            raise failure
        if reporting_error is not None:
            raise catalog.WorkspaceError(
                _report_message(
                    f"HTML evidence report incomplete: {reporting_error}", pending_report
                )
            ) from reporting_error
    finally:
        # Keep an unpublished report for diagnostics instead of deleting it.
        if pending_report.exists():
            print(f"Unpublished HTML diagnostics: {pending_report}", file=sys.stderr)


def _report_message(message: str, pending: Path) -> str:
    for value in (pending.resolve().as_uri(), str(pending), pending.name):
        message = message.replace(value, "[report pending finalization]")
    return message


def _run_report_child(args: list[str], *, cwd: Path, env: dict[str, str], hidden: str) -> None:
    """Stream pytest progress while hiding only its unpublished report filename."""
    with subprocess.Popen(
        args,
        cwd=cwd,
        env=env,
        text=True,
        errors="replace",
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        bufsize=1,
    ) as process:
        assert process.stdout is not None

        def drain() -> None:
            for line in process.stdout:
                print(_report_message(line, Path(hidden)), end="", flush=True)
            process.wait()

        try:
            try:
                drain()
            except KeyboardInterrupt:
                # Keep draining: cleanup can fill the pipe before releasing owners.
                drain()
                raise
        except BaseException:
            if process.poll() is None:
                process.kill()
            process.wait()
            raise
        if process.returncode:
            raise subprocess.CalledProcessError(
                process.returncode, [_report_message(arg, Path(hidden)) for arg in args]
            )


def active_environment(root: Path) -> Path:
    errors = inspect(root)
    if errors:
        raise catalog.WorkspaceError("Workspace is not ready: " + "; ".join(errors))
    state = get_state(root)
    assert state is not None
    return Path(state["env"])


def run_command(root: Path, arguments: list[str]) -> None:
    if not arguments:
        raise catalog.WorkspaceError(
            "Pass a command: python scripts/ws.py exec -- autospan plugins"
        )
    env_dir = active_environment(root)
    process_env = execution_environment(env_dir)
    # Windows executable lookup can use the parent process's PATH even when a
    # different PATH is passed to the child. Resolve before spawning the command.
    executable = shutil.which(arguments[0], path=process_env["PATH"])
    run([executable or arguments[0], *arguments[1:]], cwd=root, env=process_env)


def execution_environment(env_dir: Path) -> dict[str, str]:
    process_env = os.environ.copy()
    process_env["VIRTUAL_ENV"] = str(env_dir)
    process_env["PATH"] = (
        str(python_path(env_dir).parent) + os.pathsep + process_env.get("PATH", "")
    )
    process_env.pop("PYTHONPATH", None)
    process_env.pop("PYTHONHOME", None)
    process_env["PYTHONNOUSERSITE"] = "1"
    return process_env


@contextmanager
def operation_lock(root: Path) -> Iterator[None]:
    """Reject concurrent workspace mutations; the OS releases locks after a crash."""
    path = root / ".generated" / "operation.lock"
    if path.parent.is_symlink() or (path.parent.exists() and not path.parent.is_dir()):
        raise catalog.WorkspaceError(".generated/ must be a directory, not a symlink")
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.is_symlink():
        raise catalog.WorkspaceError("Workspace operation lock must not be a symlink")
    with path.open("a+b") as handle:
        if handle.tell() == 0:
            handle.write(b"0")
            handle.flush()
        handle.seek(0)
        try:
            if os.name == "nt":
                import msvcrt

                msvcrt.locking(handle.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl

                fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as exc:
            raise catalog.WorkspaceError(
                "Another workspace operation is running; retry when it finishes"
            ) from exc
        try:
            yield
        finally:
            handle.seek(0)
            if os.name == "nt":
                msvcrt.locking(handle.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
